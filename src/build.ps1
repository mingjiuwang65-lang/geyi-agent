# build.ps1 - 用系统自带 .NET Framework 编译器生成 格一代理.exe
# 不需要 Visual Studio / NuGet / 第三方工具；Win7 SP1 / Win10 / Win11 均可编译。
# 源码是 UTF-8，编译时把全部非 ASCII 字符转成 \uXXXX，避免 csc 代码页把中文写坏。
# 版本单点来源: src/version.txt (VER/BUILD/CFGVER)，注入 AssemblyVersion / C# 常量 / app_version.txt。
# 产物: exe_delivery\格一代理.exe + exe_delivery\publish\ (可直接发布的升级点与清单)。

$ErrorActionPreference = 'Stop'
# ASCII-safe product name (the app name contains non-ASCII; build.ps1 may be
# executed through `powershell.exe -File` which decodes the script using the
# OEM code page and would mangle literal non-ASCII characters).
$asciiAppName = 'GeYiProxy'
# GEYI_BUILD_ROOT lets the script run from an ASCII staging copy (the Chinese
# path breaks `powershell.exe -File` code-page handling on some hosts).
$root = $env:GEYI_BUILD_ROOT
if ([string]::IsNullOrEmpty($root)) { $root = Split-Path -Parent $MyInvocation.MyCommand.Definition }
$delivery = Split-Path -Parent $root
$payload = Join-Path $delivery 'payload'
$publish = Join-Path $delivery 'publish'
$srcFile = Join-Path $root '格一代理.cs'
if (-not (Test-Path $srcFile)) {
  # fall back to the only *.cs in the folder (name contains non-ASCII)
  $cs = @(Get-ChildItem -Path $root -Filter '*.cs' -File | Where-Object { $_.Name -notlike '*.bak*' })
  if ($cs.Count -gt 0) { $srcFile = $cs[0].FullName }
}
$verFile = Join-Path $root 'version.txt'
$icoFile = Join-Path $root 'geyi.ico'
$outExe = Join-Path $delivery '格一代理.exe'
$tmpCs = Join-Path $env:TEMP 'GeYiProxy_main.ascii.cs'
$tmpRes = Join-Path $env:TEMP 'GeYiProxy_resources.cs'

function Convert-ToAsciiSource([string]$text) {
  $sb = New-Object System.Text.StringBuilder
  foreach ($ch in $text.ToCharArray()) {
    $code = [int][char]$ch
    if ($code -gt 127) { [void]$sb.Append('\u' + $code.ToString('X4')) }
    else { [void]$sb.Append($ch) }
  }
  return $sb.ToString()
}

# --- 0) version (single source of truth) ---
$vv = @{}
foreach ($l in ([IO.File]::ReadAllText($verFile, [Text.Encoding]::UTF8) -split "`r?`n")) {
  if ($l -match '^([A-Z]+)=(.*)$') { $vv[$Matches[1]] = $Matches[2].Trim() }
}
$ver = $vv['VER']; $build = $vv['BUILD']; $cfgver = $vv['CFGVER']
if (-not $ver) { throw 'version.txt: VER missing' }
$parts = $ver.Split('.')
while ($parts.Count -lt 4) { $parts += '0' }
$ver4 = ($parts[0..3] -join '.')
Write-Host ('VERSION=' + $ver + '  BUILD=' + $build + '  CFGVER=' + $cfgver + '  ASM=' + $ver4)

# The installed version file is a payload item so the exe embeds and refreshes it.
$encUtf8 = New-Object System.Text.UTF8Encoding($false)
$encUtf8Bom = New-Object System.Text.UTF8Encoding($true)
[IO.File]::WriteAllText((Join-Path $payload 'app_version.txt'),
  ('VER=' + $ver + "`r`nBUILD=" + $build + "`r`nCFGVER=" + $cfgver + "`r`nPRODUCT=" + $asciiAppName + "`r`n"), $encUtf8Bom)

# --- 1) main source with version placeholders replaced ---
$main = [IO.File]::ReadAllText($srcFile, [Text.Encoding]::UTF8)
$main = $main.Replace('__VER4__', $ver4).Replace('__VER__', $ver).Replace('__BUILD__', $build).Replace('__CFGVER__', $cfgver)
$mainAscii = Convert-ToAsciiSource $main
[IO.File]::WriteAllText($tmpCs, $mainAscii, [Text.Encoding]::ASCII)

# --- 2) embedded resources (every file in payload) ---
$files = @(Get-ChildItem -Path $payload -File | Sort-Object Name)
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('namespace GeYiProxy {')
[void]$sb.AppendLine('  internal static class Res {')
[void]$sb.AppendLine('    private static readonly string[] N = new string[] {')
foreach ($f in $files) { [void]$sb.AppendLine('      "' + $f.Name + '",') }
[void]$sb.AppendLine('    };')
[void]$sb.AppendLine('    private static readonly string[] D = new string[] {')
foreach ($f in $files) {
  $b64 = [Convert]::ToBase64String([IO.File]::ReadAllBytes($f.FullName))
  $pieces = @()
  for ($i = 0; $i -lt $b64.Length; $i += 4000) {
    $len = [Math]::Min(4000, $b64.Length - $i)
    $pieces += ('"' + $b64.Substring($i, $len) + '"')
  }
  [void]$sb.AppendLine('      ' + ($pieces -join ' + ') + ',')
}
[void]$sb.AppendLine('    };')
[void]$sb.AppendLine('    public static string[] Names() { return N; }')
[void]$sb.AppendLine('    public static byte[] Get(string name) { for (int i = 0; i < N.Length; i++) if (N[i] == name) return System.Convert.FromBase64String(D[i]); return null; }')
[void]$sb.AppendLine('  }')
[void]$sb.AppendLine('}')
[IO.File]::WriteAllText($tmpRes, $sb.ToString(), [Text.Encoding]::ASCII)

# --- 3) branded win32 icon (generated by make_icons.py) ---
$iconArg = ''
if (Test-Path $icoFile) { $iconArg = '/win32icon:"' + $icoFile + '" ' }
else { Write-Host 'WARN: geyi.ico missing, exe will use the default icon' }

# --- 4) compile ---
$cp = New-Object System.CodeDom.Compiler.CompilerParameters
$cp.GenerateExecutable = $true
$cp.GenerateInMemory = $false
$cp.IncludeDebugInformation = $false
$cp.TreatWarningsAsErrors = $false
$cp.OutputAssembly = $outExe
$cp.MainClass = 'GeYiProxy.Program'
$cp.CompilerOptions = $iconArg + '/target:winexe /platform:anycpu /optimize+ /nowarn:1701,1702'
foreach ($a in @('System.dll','System.Core.dll','System.Windows.Forms.dll','System.Drawing.dll','System.Security.dll','Microsoft.CSharp.dll')) {
  [void]$cp.ReferencedAssemblies.Add($a)
}
$provider = New-Object Microsoft.CSharp.CSharpCodeProvider
$result = $provider.CompileAssemblyFromSource($cp, @($mainAscii, $sb.ToString()))
if ($result.Errors.HasErrors) {
  Write-Host '=== COMPILE FAILED ==='
  foreach ($e in $result.Errors) { if (-not $e.IsWarning) { Write-Host ($e.ToString()) } }
  exit 1
}

# --- 5) publish point + ready-to-use update.manifest ---
if (-not (Test-Path $publish)) { New-Item -ItemType Directory -Path $publish -Force | Out-Null }
$publishExe = Join-Path $publish '格一代理.exe'
if (-not (Test-Path $publishExe)) {
  $pe = @(Get-ChildItem -Path $publish -Filter '*.exe' -File -ErrorAction SilentlyContinue)
  if ($pe.Count -gt 0) { $publishExe = $pe[0].FullName }
  else { $publishExe = Join-Path $publish 'geyi_agent.exe' }
}
Copy-Item $outExe $publishExe -Force
$sha = New-Object System.Security.Cryptography.SHA256Managed
try {
  $hash = (($sha.ComputeHash([IO.File]::ReadAllBytes($outExe)) | ForEach-Object { $_.ToString('X2') }) -join '')
} finally { $sha.Dispose() }
$size = (Get-Item $outExe).Length
$man = 'VER=' + $ver + "`r`n" +
       'BUILD=' + $build + "`r`n" +
       'URL=geyi_agent.exe' + "`r`n" +
       'SHA256=' + $hash + "`r`n" +
       'SIZE=' + $size + "`r`n" +
       'PHASE=canary' + "`r`n" +
       'CANARY_HOSTS=mingjiu-pc' + "`r`n" +
       'NOTE=GeYiProxy ' + $ver + ' 5-node status/auto-switch/random-rotation/CA-root-chain' + "`r`n"
[IO.File]::WriteAllText((Join-Path $publish 'update.manifest'), $man, $encUtf8Bom)

Write-Host ('PAYLOAD_FILES=' + $files.Count)
foreach ($f in $files) { Write-Host ('  ' + $f.Name + '  ' + $f.Length + 'B') }
Write-Host ('OUTPUT=' + $outExe)
Write-Host ('SIZE=' + $size + 'B')
Write-Host ('SHA256=' + $hash)
Write-Host ('PUBLISH=' + $publish)
Write-Host 'COMPILE=OK'
